/** Pull the drawing out of a Lucide file, dropping its <svg> wrapper. */
function innerMarkup(name) {
  const svg = readFileSync(join(ICON_DIR, `${name}.svg`), 'utf8');
  const body = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));
  // Collapse the pretty-printing; this ends up inside a JS string literal.
  return body.replace(/\s+/g, ' ').replace(/>\s+</g, '><').trim();
}

const entries = Object.entries(ICON_SOURCES).map(([name, source]) => {
  const markup = innerMarkup(source);
  if (!markup) throw new Error(`no markup extracted for ${source}`);
  return `  '${name}': '${markup.replace(/'/g, "\\'")}',`;
});

const file = `/**
 * Every icon, in one place.
 *
 * GENERATED by scripts/build-icons.mjs - do not edit by hand. Add a name to
 * ICON_SOURCES there and re-run it.
 *
 * The drawings are Lucide (https://lucide.dev), ISC licensed, used under those
 * terms. They share one grid - 24x24, stroke 2, round caps and joins - which is
 * the entire point of this file: these icons were previously drawn by hand in
 * six different modules and had drifted to four different stroke widths.
 *
 * Only the path data is stored. Callers choose the size and stroke, because a
 * 15px lane marker and a 22px dock icon want different weights of one shape.
 */

/** Icon name -> the markup that goes inside an <svg>. */
export const ICONS = Object.freeze({
${entries.join('\n')}
});

/** Every name this module knows, for tests and for pickers. */
export const ICON_NAMES = Object.freeze(Object.keys(ICONS));

export function hasIcon(name) {
  return Object.hasOwn(ICONS, String(name ?? ''));
}

/**
 * One icon as an SVG string, for the content scripts.
 *
 * They build their UI with innerHTML and have no React, so markup is what they
 * need. An unknown name returns an empty string rather than throwing: a missing
 * icon should be a gap in a toolbar, not a dead page on someone's job search.
 *
 * @param {string} name
 * @param {{size?: number, stroke?: number, className?: string, title?: string}} [options]
 */
export function iconMarkup(name, { size = 16, stroke = 2, className = '', title = '' } = {}) {
  const body = ICONS[name];
  if (!body) return '';
  const label = title
    ? \`role="img" aria-label="\${title}"\`
    : 'aria-hidden="true" focusable="false"';
  return (
    \`<svg viewBox="0 0 24 24" width="\${size}" height="\${size}" fill="none"\` +
    \` stroke="currentColor" stroke-width="\${stroke}" stroke-linecap="round"\` +
    \` stroke-linejoin="round"\${className ? \` class="\${className}"\` : ''} \${label}>\` +
    \`\${body}</svg>\`
  );
}
`;

