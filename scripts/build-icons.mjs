/**
 * Generate src/core/icons.js from Lucide.
 *
 *     node scripts/build-icons.mjs
 *
 * Every icon in this extension used to be drawn by hand, one at a time, in
 * whichever file needed it - which is why the stroke widths had drifted between
 * 1.6 and 2 and no two files agreed on a corner radius. Lucide is one grid:
 * 24x24, stroke 2, round caps and joins, two thousand icons that all look
 * related.
 *
 * The library is a DEV dependency only. Shipping 21MB of SVG to draw forty
 * icons would be absurd, and a content script cannot reach node_modules anyway,
 * so this pulls out the markup we actually use and writes it into one module.
 * Re-run it after adding a name to ICON_SOURCES below.
 *
 * The generated file is committed, so a clean checkout builds without the dev
 * dependency present at all.
 */

